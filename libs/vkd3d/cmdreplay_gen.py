#!/usr/bin/env python3
"""Generates cmdreplay_gen.h for cmdreplay.c (miles-bench deferred command recording).

    python3 libs/vkd3d/cmdreplay_gen.py

For every device function vkd3d loads (vulkan_procs.h):
  - vkCmd* whose arguments after the command buffer are all plain values: an op struct, a recorder
    (rp_vkCmdX) that appends the op to the command buffer's stream, and its replay;
  - every other vkCmd* without a hand-written rp_vkCmdX in cmdreplay.c: a drain wrapper (the worker
    finishes everything published, then the call goes straight to the driver on this thread);
  - vkDestroy* / vkFree* / vkResetDescriptorPool: a guard that waits for the worker to finish
    every published op first (a replayed op may still name the object).
Any other function that can see a command buffer must be hand-written in cmdreplay.c, or this
script fails: a tagged handle must never reach the driver.
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, "..", ".."))
header = open(os.path.join(root, "khronos/Vulkan-Headers/include/vulkan/vulkan_core.h")).read()
procs = open(os.path.join(here, "vulkan_procs.h")).read()
impl = open(os.path.join(here, "cmdreplay.c")).read()

device_fns = re.findall(r"^VK_DEVICE(?:_EXT)?_PFN\((vk\w+)\)", procs, re.M)
hand = set(re.findall(r"^static VKAPI_ATTR \w+ VKAPI_CALL rp_(vk\w+)\(", impl, re.M))
hand |= set(re.findall(r"^RP_COPY_RECORDER\((vk\w+),", impl, re.M))

protos = {}
for ret, name, params in re.findall(r"VKAPI_ATTR (\w+) VKAPI_CALL (vk\w+)\(\s*(.*?)\);", header, re.S):
    plist = []
    for p in params.split(","):
        p = " ".join(p.split())
        m = re.match(r"(.*?)\s*(\w+)(\[\d+\])?$", p)
        ptype, pname, arr = m.group(1), m.group(2), m.group(3) or ""
        plist.append((ptype, pname, arr))
    protos[name] = (ret, plist)

# Types through which a command buffer handle can reach a function.
CB_TYPES = ("VkCommandBuffer", "VkSubmitInfo", "VkSubmitInfo2", "VkCommandBufferSubmitInfo",
            "VkDebugUtilsObjectNameInfoEXT", "VkDebugUtilsObjectTagInfoEXT")
GUARDED = lambda n: (n.startswith(("vkDestroy", "vkFree")) or n == "vkResetDescriptorPool") and n not in (
    "vkDestroyDevice", "vkDestroyCommandPool", "vkFreeCommandBuffers")


# Destroys of the form (device, handle, pAllocator) are queued behind the published ops instead of
# waiting for them; fences, semaphores, swapchains and caches stay synchronous (a caller may rely on
# them being gone, e.g. a swapchain's surface being free again).
DEFERRED = lambda n, ret, pl: (ret == "void" and len(pl) == 3 and pl[0][0] == "VkDevice"
        and pl[2][0] == "const VkAllocationCallbacks*" and n not in (
        "vkDestroyFence", "vkDestroySemaphore", "vkDestroySwapchainKHR", "vkDestroyPipelineCache"))


def by_value(ptype, arr):
    return "*" not in ptype and not arr


def decl(plist):
    return ", ".join(f"{t} {n}{a}" for t, n, a in plist)


out = ["/* Generated by cmdreplay_gen.py from vulkan_core.h and vulkan_procs.h; do not edit. */", "",
       "#ifndef RP_GEN_INSTALL", ""]
installs, drains, missing = [], [], []
for name in device_fns:
    if name not in protos:
        continue
    ret, plist = protos[name]
    sees_cb = any(any(re.search(rf"\b{t}\b", p[0]) for t in CB_TYPES) for p in plist)
    if name.startswith("vkCmd") and plist[0][0] == "VkCommandBuffer":
        if name in hand:
            installs.append(name)
            continue
        if any(re.search(rf"\b{t}\b", p[0]) for t in CB_TYPES for p in plist[1:]):
            missing.append(name)
            continue
        args = ", ".join(n for _, n, _ in plist[1:])
        if all(by_value(t, a) for t, _, a in plist[1:]) and not any(re.search(rf"\b{t}\b", p[0]) for t in CB_TYPES for p in plist[1:]):
            fields = "".join(f"    {t} {n};\n" for t, n, _ in plist[1:])
            sets = "".join(f"    op->{n} = {n};\n" for _, n, _ in plist[1:])
            oargs = ", ".join(f"op->{n}" for _, n, _ in plist[1:])
            out.append(f"struct rp_op_{name}\n{{\n    struct rp_op h;\n{fields}}};\n")
            out.append(f"static void rp_replay_{name}(VkCommandBuffer cb, const struct rp_op *h)\n{{\n"
                       + (f"    const struct rp_op_{name} *op = (const void *)h;\n" if plist[1:] else "    (void)h;\n")
                       + f"    rp_real.{name}(cb{', ' if oargs else ''}{oargs});\n}}\n")
            out.append(f"static VKAPI_ATTR void VKAPI_CALL rp_{name}({decl(plist)})\n{{\n"
                       + (f"    struct rp_op_{name} *op;\n\n" if plist[1:] else "")
                       + f"    if (!RP_TAGGED(commandBuffer))\n"
                       f"    {{\n        rp_real.{name}(commandBuffer{', ' if args else ''}{args});\n        return;\n    }}\n"
                       + (f"    op = rp_op_alloc(RP_CB(commandBuffer), rp_replay_{name}, sizeof(*op));\n{sets}}}\n" if plist[1:] else
                          f"    rp_op_alloc(RP_CB(commandBuffer), rp_replay_{name}, sizeof(struct rp_op_{name}));\n}}\n"))
        else:
            idx = len(drains)
            drains.append(name)
            out.append(f"static VKAPI_ATTR {ret} VKAPI_CALL rp_{name}({decl(plist)})\n{{\n"
                       f"    if (RP_TAGGED(commandBuffer))\n"
                       f"        commandBuffer = rp_drain_for_direct(RP_CB(commandBuffer), {idx});\n"
                       f"    {'return ' if ret != 'void' else ''}rp_real.{name}(commandBuffer{', ' if args else ''}{args});\n}}\n")
        installs.append(name)
    elif name in hand:
        installs.append(name)
    elif sees_cb:
        missing.append(name)
    elif GUARDED(name) and DEFERRED(name, ret, plist):
        h = plist[1][1]
        out.append(f"struct rp_op_{name}\n{{\n    struct rp_op h;\n    VkDevice device;\n    {plist[1][0]} {h};\n"
                   f"    const VkAllocationCallbacks *pAllocator;\n}};\n")
        out.append(f"static void rp_replay_{name}(VkCommandBuffer cb, const struct rp_op *h)\n{{\n"
                   f"    const struct rp_op_{name} *op = (const void *)h;\n"
                   f"    rp_real.{name}(op->device, op->{h}, op->pAllocator);\n}}\n")
        out.append(f"static VKAPI_ATTR void VKAPI_CALL rp_{name}({decl(plist)})\n{{\n"
                   f"    struct rp_op_{name} *op;\n    struct rp_chunk *k;\n\n"
                   f"    if (!{h} || !(k = rp_defer_chunk(rp_replay_{name}, sizeof(*op))))\n"
                   f"    {{\n        rp_real.{name}(device, {h}, pAllocator);\n        return;\n    }}\n"
                   f"    op = (void *)k->data;\n    op->device = device;\n    op->{h} = {h};\n    op->pAllocator = pAllocator;\n"
                   f"    rp_publish_chunk(k);\n}}\n")
        installs.append(name)
    elif GUARDED(name):
        args = ", ".join(n for _, n, _ in plist)
        out.append(f"static VKAPI_ATTR {ret} VKAPI_CALL rp_{name}({decl(plist)})\n{{\n"
                   f"    rp_guard();\n"
                   f"    {'return ' if ret != 'void' else ''}rp_real.{name}({args});\n}}\n")
        installs.append(name)

if missing:
    sys.exit("cmdreplay_gen.py: these functions can see a command buffer but have no hand-written "
             "wrapper in cmdreplay.c: " + ", ".join(missing))

out.append("static const char *const rp_drain_names[] =\n{")
out += [f'    "{n}",' for n in drains] or ['    "",']
out.append("};\n")
out.append(f"#define RP_DRAIN_COUNT {max(len(drains), 1)}\n")
out.append("#else\n")
out.append("static void rp_install_procs(struct vkd3d_vk_device_procs *vk)\n{")
for n in installs:
    out.append(f"    if (vk->{n})\n        vk->{n} = rp_{n};")
out.append("}\n")
out.append("#endif")
open(os.path.join(here, "cmdreplay_gen.h"), "w").write("\n".join(out) + "\n")
print(f"cmdreplay_gen.h: {len(installs)} wrappers, {len(drains)} drain fallbacks, "
      f"{len(hand)} hand-written")
